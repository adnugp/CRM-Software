const test = require('node:test');
const assert = require('node:assert/strict');
const {mkdtempSync, writeFileSync, readFileSync, rmSync} = require('node:fs');
const {tmpdir} = require('node:os');
const {join} = require('node:path');
const {spawnSync} = require('node:child_process');
const {initializeApp, deleteApp} = require('firebase-admin/app');
const {getFirestore, Timestamp} = require('firebase-admin/firestore');
assert.ok(process.env.FIRESTORE_EMULATOR_HOST, 'Emulator required');
assert.equal(process.env.GCLOUD_PROJECT, 'demo-crm-test');
const app = initializeApp({projectId: 'demo-crm-test'}, 'migration-tool-tests');
const db = getFirestore(app);
const directory = mkdtempSync(join(tmpdir(), 'crm-migration-emulator-'));
test.after(async () => { await deleteApp(app); rmSync(directory, {recursive: true, force: true}); });
function run(script, extra) {
  return spawnSync(process.execPath, [`scripts/${script}.mjs`, '--project', 'demo-crm-test', '--workspace', 'migration-test', ...extra], {encoding: 'utf8', timeout: 20000});
}
test('dry-run/apply/replay/rollback and backup/restore obey ownership and target guards', async () => {
  await db.doc('tasks/original-task-id').set({name: 'Legacy', company: 'Sadeem', createdAt: Timestamp.fromMillis(123456)});
  const mapping = join(directory, 'mapping.json');
  writeFileSync(mapping, JSON.stringify({workspaceId: 'migration-test', migrationId: 'migration-v1', actorUid: 'admin', divisions: [{id: 'one', name: 'One'}, {id: 'two', name: 'Two'}], members: {admin: {role: 'admin', active: true}}, recordDivisions: {'tasks/original-task-id': 'one'}}));
  const dry = run('migrate-workspace', ['--mapping', mapping, '--output', join(directory, 'dry.json')]);
  assert.equal(dry.status, 0, dry.stderr); assert.equal((await db.doc('workspaces/migration-test').get()).exists, false);
  const rejected = run('migrate-workspace', ['--mapping', mapping, '--output', join(directory, 'wrong.json'), '--apply', '--confirm-project', 'wrong-project']);
  assert.notEqual(rejected.status, 0);
  const snapshot = join(directory, 'apply.json');
  const apply = run('migrate-workspace', ['--mapping', mapping, '--output', snapshot, '--apply', '--confirm-project', 'demo-crm-test']);
  assert.equal(apply.status, 0, apply.stderr);
  const target = db.doc('workspaces/migration-test/tasks/original-task-id');
  assert.equal((await target.get()).data().divisionId, 'one');
  assert.equal((await target.get()).data().createdAt.toMillis(), 123456);
  const replay = run('migrate-workspace', ['--mapping', mapping, '--output', join(directory, 'replay.json'), '--apply', '--confirm-project', 'demo-crm-test']);
  assert.equal(replay.status, 0, replay.stderr); assert.equal(JSON.parse(replay.stdout).writes.length, 0);
  const backupFile = join(directory, 'backup.json');
  assert.equal(run('backup-workspace', ['--output', backupFile]).status, 0);
  await target.delete();
  const restore = run('restore-workspace', ['--snapshot', backupFile, '--apply', '--confirm-project', 'demo-crm-test']);
  assert.equal(restore.status, 0, restore.stderr); assert.equal((await target.get()).data().createdAt.toMillis(), 123456);
  await db.doc('workspaces/migration-test/tasks/unrelated').set({name: 'Unrelated'});
  await target.update({name: 'Modified by user'});
  const rollback = run('rollback-migration', ['--snapshot', snapshot, '--apply', '--confirm-project', 'demo-crm-test']);
  assert.equal(rollback.status, 0, rollback.stderr);
  assert.equal((await target.get()).data().name, 'Modified by user');
  assert.equal((await db.doc('workspaces/migration-test/tasks/unrelated').get()).exists, true);
  assert.equal((await db.doc('workspaces/migration-test/members/admin').get()).exists, false);
  const conflict = run('restore-workspace', ['--snapshot', backupFile, '--apply', '--confirm-project', 'demo-crm-test']);
  assert.equal(conflict.status, 1); assert.equal((await db.doc('workspaces/migration-test/members/admin').get()).exists, false);
  assert.equal(JSON.parse(readFileSync(snapshot, 'utf8')).projectId, 'demo-crm-test');
});
